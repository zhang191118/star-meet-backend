// GetEmotionReply 根据角色风格和情绪获取回复
func GetEmotionReply(style, emotion string) string {
	if templates, ok := StyleEmotionTemplates[style]; ok {
		if reply, ok := templates[emotion]; ok {
			return reply
		}
	}

	// 默认回复
	defaultReplies := map[string]string{
		"happy":   "看到你开心真好~ 😊",
		"comfort": "我一直都在... 🤗",
		"apology": "别生气啦~ 💕",
		"love":    "我也喜欢你~ 💖",
		"neutral": "嗯~ 😐",
		"excited": "你好棒！✨",
		"help":    "我听着呢~ 🌟",
		"play":    "一起玩吧~ 🎮",
	}

	if reply, ok := defaultReplies[emotion]; ok {
		return reply
	}

	return ""
}
